//! Testnet-10 submission tool for the mass-limit checks (research G1–G3).
//!
//! Testnet-10 only. The node must report network `testnet-10`, and mainnet
//! addresses are refused. The private key lives in the repo-root `.env` (git-ignored)
//! as TN10_PRIVATE_KEY; the endpoint comes from TN10_WRPC_URL, or the public
//! resolver when unset.

mod anchor;
mod cases;
mod net;
mod probe;

use std::{collections::BTreeMap, path::PathBuf, process::ExitCode};

use kaspa_addresses::{Address, Prefix, Version};
use secp256k1::{Keypair, SECP256K1, SecretKey};

const KEY_VAR: &str = "TN10_PRIVATE_KEY";
const URL_VAR: &str = "TN10_WRPC_URL";

fn env_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../.env")
}

/// Minimal KEY=VALUE reader for the git-ignored `.env`; process env wins.
fn load_env() -> BTreeMap<String, String> {
    let mut map = BTreeMap::new();
    if let Ok(text) = std::fs::read_to_string(env_path()) {
        for line in text.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            if let Some((k, v)) = line.split_once('=') {
                map.insert(k.trim().to_string(), v.trim().to_string());
            }
        }
    }
    for var in [KEY_VAR, URL_VAR] {
        if let Ok(v) = std::env::var(var) {
            map.insert(var.to_string(), v);
        }
    }
    map
}

fn keypair(env: &BTreeMap<String, String>) -> Result<Keypair, String> {
    let hex = env.get(KEY_VAR).ok_or(format!("{KEY_VAR} not set; run `keygen` first"))?;
    let bytes = decode_hex(hex)?;
    let sk = SecretKey::from_slice(&bytes).map_err(|e| format!("bad {KEY_VAR}: {e}"))?;
    Ok(Keypair::from_secret_key(SECP256K1, &sk))
}

pub fn address(kp: &Keypair) -> Address {
    let (xonly, _) = kp.x_only_public_key();
    Address::new(Prefix::Testnet, Version::PubKey, &xonly.serialize())
}

fn decode_hex(s: &str) -> Result<Vec<u8>, String> {
    if s.len() % 2 != 0 {
        return Err("odd-length hex".into());
    }
    (0..s.len()).step_by(2).map(|i| u8::from_str_radix(&s[i..i + 2], 16).map_err(|e| e.to_string())).collect()
}

fn encode_hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

fn keygen() -> Result<(), String> {
    let env = load_env();
    if env.contains_key(KEY_VAR) {
        return Err(format!("{KEY_VAR} already exists in .env; refusing to overwrite"));
    }
    let (sk, _) = SECP256K1.generate_keypair(&mut secp256k1::rand::thread_rng());
    let kp = Keypair::from_secret_key(SECP256K1, &sk);
    let line = format!("{KEY_VAR}={}\n", encode_hex(&sk.secret_bytes()));
    let path = env_path();
    let mut text = std::fs::read_to_string(&path).unwrap_or_default();
    if !text.is_empty() && !text.ends_with('\n') {
        text.push('\n');
    }
    text.push_str("# testnet-10 only; generated by `cargo run -p tn10 -- keygen`\n");
    text.push_str(&line);
    std::fs::write(&path, text).map_err(|e| e.to_string())?;
    println!("Wrote {KEY_VAR} to {} (git-ignored).", path.display());
    println!("Fund this testnet-10 address from the faucet: {}", address(&kp));
    Ok(())
}

async fn info() -> Result<(), String> {
    let env = load_env();
    let kp = keypair(&env)?;
    let addr = address(&kp);
    let client = net::connect(env.get(URL_VAR).cloned()).await?;
    let utxos = net::utxos(&client, &addr).await?;
    let total: u64 = utxos.iter().map(|u| u.utxo_entry.amount).sum();
    println!("Address: {addr}");
    println!("UTXOs: {}  balance: {} KAS", utxos.len(), total as f64 / 1e8);
    for u in &utxos {
        println!("  {}:{}  {} KAS  creation DAA {}", u.outpoint.transaction_id, u.outpoint.index, u.utxo_entry.amount as f64 / 1e8, u.utxo_entry.block_daa_score);
    }
    Ok(())
}

/// M7 Stage 4 (spec D103): rebuild the anchor proof of a fresh real block from RPC and run
/// every self-check (mergeset order, parent commitment, full KIP-21 recomputation against the
/// header) without submitting anything. D = the sink's DAA score + 100 (about 10 s ahead).
/// With `n` > 0, also rebuilds and checks the next `n` chain blocks after the start and
/// tallies their mergeset sizes and the mergeset order that matched.
async fn anchor_check(n: usize) -> Result<(), String> {
    use kaspa_rpc_core::api::rpc::RpcApi;
    let env = load_env();
    let kp = keypair(&env)?;
    let client = net::connect(env.get(URL_VAR).cloned()).await?;
    let ctx = probe::Ctx { client, addr: address(&kp), sk: kp.secret_bytes(), report: vec![] };
    let start = ctx.client.get_block_dag_info().await.map_err(|e| e.to_string())?.sink;
    let sdaa = ctx.client.get_block(start, false).await.map_err(|e| e.to_string())?.header.daa_score;
    let a = anchor::rpc_anchor(&ctx, start, sdaa + 100).await?;
    println!("anchor-check OK: D = {}, X {} (DAA {}), P {} (DAA {}); every self-check passed", a.d, a.x.sim.hash, a.x.sim.daa_score, a.p.sim.hash, a.p.sim.daa_score);
    if n > 0 {
        let vc = ctx.client.get_virtual_chain_from_block(start, false, None).await.map_err(|e| e.to_string())?;
        let mut tally = std::collections::BTreeMap::<(usize, usize), (usize, usize)>::new(); // (blues, reds) -> (blocks, order-0 matches)
        let mut orders = [0usize; anchor::ORDERS.len()];
        for h in vc.added_chain_block_hashes.iter().take(n) {
            let b = anchor::anchor_from_rpc(&ctx, *h).await?;
            orders[b.order] += 1;
            let e = tally.entry((b.mergeset_blues, b.mergeset_reds)).or_default();
            e.0 += 1;
            e.1 += (b.order == 0) as usize;
        }
        let checked: usize = orders.iter().sum();
        println!("anchor-check scan: {checked} consecutive chain blocks after {start} rebuilt; every recomputation = header");
        for (i, c) in orders.iter().enumerate() {
            println!("  order [{i}] {}: {c} blocks", anchor::ORDERS[i]);
        }
        for ((bl, rd), (c, o0)) in &tally {
            println!("  mergeset {bl} blues + {rd} reds: {c} blocks, consensus order matched in {o0}");
        }
    }
    Ok(())
}

async fn run_probes(which: &str) -> Result<(), String> {
    let env = load_env();
    let kp = keypair(&env)?;
    let addr = address(&kp);
    let client = net::connect(env.get(URL_VAR).cloned()).await?;
    let mut ctx = probe::Ctx { client, addr, sk: kp.secret_bytes(), report: vec![] };
    println!("{}", cases::HEADER);
    let all = which == "all";
    if all || which == "baseline" { cases::baseline(&mut ctx).await?; }
    if all || which == "storage" { cases::storage_bounds(&mut ctx).await?; }
    if all || which == "transient" { cases::transient_bounds(&mut ctx).await?; }
    if all || which == "dust" { cases::dust(&mut ctx).await?; }
    if all || which == "buy" { cases::buy(&mut ctx).await?; }
    if all || which == "buy-m1" { cases::buy_m1(&mut ctx).await?; }
    if all || which == "claim" { cases::claim(&mut ctx).await?; }
    if all || which == "close-m2" { cases::close_m2(&mut ctx).await?; }
    // M7: draw-m3 runs the draw-m7 sequence (the TEST-ONLY seed is deleted, D101).
    if which == "draw-m3" { cases::draw_m7(&mut ctx, "draw-m3").await?; }
    if all || which == "draw-m7" { cases::draw_m7(&mut ctx, "draw-m7").await?; }
    if all || which == "void-m7" { cases::void_m7(&mut ctx).await?; }
    if all || which == "claim-m4" { cases::claim_m4(&mut ctx).await?; }
    if all || which == "vault-m5" { cases::vault_m5(&mut ctx).await?; }
    // M6: not in `all` (it locks about 160 KAS: an instance genesis and 30 accepted buys).
    if which == "conflict-m6" { cases::conflict_m6(&mut ctx).await?; }
    for k in [16usize, 32, 62] {
        if all || which == format!("close{k}") { cases::close(&mut ctx, k).await?; }
    }
    let path = std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(format!("results-{which}.md"));
    let mut text = format!("{}\n", cases::HEADER);
    for r in &ctx.report {
        text.push_str(r);
        text.push('\n');
    }
    std::fs::write(&path, text).map_err(|e| e.to_string())?;
    println!("Wrote {}", path.display());
    Ok(())
}

/// Stack size of the thread that runs the probes and of the runtime's worker threads (M5
/// Stage 7). A debug build of `probe vault-m5` overflowed the 1 MB Windows main-thread
/// stack (large builder and engine frames in unoptimised code); `--release` fit. The probes
/// now run on a spawned thread with this stack, under a runtime whose workers get the same.
const PROBE_STACK: usize = 64 * 1024 * 1024;

fn main() -> ExitCode {
    let probes = std::thread::Builder::new().name("tn10".into()).stack_size(PROBE_STACK).spawn(|| {
        let rt = tokio::runtime::Builder::new_multi_thread().enable_all().thread_stack_size(PROBE_STACK).build().expect("tokio runtime");
        rt.block_on(run())
    });
    match probes.expect("spawn the probe thread").join() {
        Ok(code) => code,
        Err(_) => {
            eprintln!("error: the probe thread panicked");
            ExitCode::FAILURE
        }
    }
}

async fn run() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let res = match args.first().map(String::as_str) {
        Some("keygen") => keygen(),
        Some("info") => info().await,
        Some("anchor-check") => anchor_check(args.get(1).and_then(|a| a.parse().ok()).unwrap_or(0)).await,
        Some("probe") => run_probes(args.get(1).map(String::as_str).unwrap_or("all")).await,
        _ => Err("usage: tn10 <keygen | info | anchor-check | probe [all|baseline|storage|transient|dust|buy|buy-m1|claim|close-m2|draw-m3|draw-m7|void-m7|claim-m4|vault-m5|conflict-m6|close16|close32|close62]> (conflict-m6 is not part of all)".into()),
    };
    match res {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("error: {e}");
            ExitCode::FAILURE
        }
    }
}
